package day03;

public class OperatorPractice1 {
    public static void main(String[] args) {
        int num1 =15;
        int num2 = 4;

        // 1. 더하기 결과 출력
        System.out.println(num1 + num2);
        // 2. 빼기 결과 출력
        System.out.println(num1 - num2);
        // 3. 곱하기 결과 출력
        System.out.println(num1 * num2);
        // 4. 나누기 몫 결과 출력
        System.out.println(num1 / num2);
        // 5. 나누기 나머지 결과 출력
        System.out.println(num1 % num2);
    }
}
